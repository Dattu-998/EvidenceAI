import os
from reportlab.pdfgen import canvas
import json

def generate_pdf():
    os.makedirs("eval/data", exist_ok=True)
    pdf_path = "eval/data/evidenceai_overview.pdf"

    c = canvas.Canvas(pdf_path)

    # Page 1
    c.drawString(50, 800, "EvidenceAI - Platform Overview")
    c.drawString(50, 780, "EvidenceAI is a next-generation document intelligence platform developed in 2024.")
    c.drawString(50, 760, "Its primary goal is to answer complex questions over unstructured documents like PDFs.")
    c.drawString(50, 740, "A key feature is strict adherence to verifiable evidence, ensuring no hallucinations.")
    c.showPage()

    # Page 2
    c.drawString(50, 800, "Core Technologies")
    c.drawString(50, 780, "The backend is built with FastAPI and Python 3.12, providing high performance.")
    c.drawString(50, 760, "For data storage, EvidenceAI utilizes PostgreSQL extended with the pgvector module.")
    c.drawString(50, 740, "This allows for efficient similarity search on embeddings generated by sentence-transformers.")
    c.showPage()

    # Page 3
    c.drawString(50, 800, "Retrieval and Refusal")
    c.drawString(50, 780, "To improve accuracy, EvidenceAI employs Hybrid Retrieval using Reciprocal Rank Fusion (RRF).")
    c.drawString(50, 760, "This combines the strengths of BM25 lexical search and vector-based semantic search.")
    c.drawString(50, 740, "If a user asks a question that cannot be answered by the document, the system initiates a refusal.")
    c.drawString(50, 720, "This evidence-based refusal is critical for maintaining trust in enterprise environments.")
    c.showPage()

    c.save()
    print(f"Generated {pdf_path}")

